function escapeRegExp(value: string): string {
    return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function normaliseOffensiveText(text: unknown): string {
    return String(text ?? '')
        .toLowerCase()
        .replace(/0/g, 'o')
        .replace(/1/g, 'i')
        .replace(/2/g, 'z')
        .replace(/3/g, 'e')
        .replace(/4/g, 'a')
        .replace(/5/g, 's')
        .replace(/6/g, 'g')
        .replace(/7/g, 't')
        .replace(/!/g, 'i')
        .replace(/@/g, 'a')
        .replace(/\$/g, 's')
}

function collapseRepeatedLetters(text: string): string {
    return text.replace(/([a-z])\1{2,}/g, '$1')
}

function buildLooseNormalisedText(text: unknown): string {
    const normalised = normaliseOffensiveText(text)
    return collapseRepeatedLetters(
        normalised.replace(/[^a-z0-9\s]/g, ' ')
    ).replace(/\s+/g, ' ').trim()
}

function buildVariantPattern(word: string): string {
    const chars = word.toLowerCase().split('')
    const parts = chars.map(char => {
        const variants = CHAR_EQUIVALENTS[char] ?? [char]
        const classPart = `[${variants.map(v => escapeRegExp(v)).join('')}]`
        return `${classPart}+`
    })
    return parts.join(`[\\s._\\-'"\\\`~*]*`)
}

function buildBoundaryPattern(word: string): RegExp {
    return new RegExp(`(^|[^a-z0-9])(${buildVariantPattern(word)})(?=$|[^a-z0-9])`, 'i')
}

function buildJoinedPattern(word: string): RegExp {
    return new RegExp(buildVariantPattern(word), 'i')
}

// Only use joined (no-boundary) matching for words >= this length.
// Short words like "nig", "ass", "cum" appear as substrings of innocent words
// ("night", "class", "document") when all spaces are stripped — boundary matching alone is sufficient.
const MIN_JOINED_LENGTH = 5

export function containsOffensiveLanguage(input: unknown, words = OFFENSIVE_WORDS): boolean {
    const looseText = buildLooseNormalisedText(input)
    const joinedText = looseText.replace(/\s+/g, '')

    for (const word of words) {
        const baseWord = collapseRepeatedLetters(normaliseOffensiveText(word).replace(/[^a-z0-9]/g, ''))
        if (!baseWord) continue

        if (buildBoundaryPattern(baseWord).test(looseText)) return true
        if (baseWord.length >= MIN_JOINED_LENGTH && buildJoinedPattern(baseWord).test(joinedText)) return true
    }

    return false
}

export function findOffensiveMatches(input: unknown, words = OFFENSIVE_WORDS): string[] {
    const looseText = buildLooseNormalisedText(input)
    const joinedText = looseText.replace(/\s+/g, '')
    const matches = new Set<string>()

    for (const word of words) {
        const baseWord = collapseRepeatedLetters(normaliseOffensiveText(word).replace(/[^a-z0-9]/g, ''))
        if (!baseWord) continue

        const boundaryMatch = buildBoundaryPattern(baseWord).test(looseText)
        const joinedMatch = baseWord.length >= MIN_JOINED_LENGTH && buildJoinedPattern(baseWord).test(joinedText)
        if (boundaryMatch || joinedMatch) matches.add(word)
    }

    return Array.from(matches)
}

export function censorOffensiveLanguage(input: unknown, words = OFFENSIVE_WORDS, mask = '****'): string {
    let result = String(input ?? '')
    const sortedWords = [...words].sort((a, b) => b.length - a.length)

    for (const word of sortedWords) {
        const baseWord = collapseRepeatedLetters(normaliseOffensiveText(word).replace(/[^a-z0-9]/g, ''))
        if (!baseWord) continue
        result = result.replace(new RegExp(buildVariantPattern(baseWord), 'gi'), mask)
    }

    return result
}

// Backward-compatible alias used by JoinForm and RecruitMemberTab
export function containsOffensiveWord(name: string): boolean {
    return containsOffensiveLanguage(name)
}
